-- Tabela para vincular usuários às filiais permitidas
CREATE TABLE FOCCO3I.TGAZIN_USUARIO_FILIAL (
    ID_USUARIO_FILIAL   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LOGIN_USUARIO       VARCHAR2(100) NOT NULL,
    EMPR_ID             NUMBER NOT NULL,
    ATIVO               CHAR(1) DEFAULT 'S' CHECK (ATIVO IN ('S', 'N')),
    DT_CADASTRO         DATE DEFAULT SYSDATE,
    DT_ALTERACAO        DATE,
    CONSTRAINT FK_UF_EMPRESA FOREIGN KEY (EMPR_ID) REFERENCES FOCCO3I.TEMPRESAS(ID)
);

-- Índices para performance
CREATE INDEX IDX_TGAZIN_UF_LOGIN ON FOCCO3I.TGAZIN_USUARIO_FILIAL(UPPER(LOGIN_USUARIO));
CREATE INDEX IDX_TGAZIN_UF_EMPR ON FOCCO3I.TGAZIN_USUARIO_FILIAL(EMPR_ID);
CREATE INDEX IDX_TGAZIN_UF_ATIVO ON FOCCO3I.TGAZIN_USUARIO_FILIAL(ATIVO);

-- Constraint única para evitar duplicidade (login + empresa)
CREATE UNIQUE INDEX IDX_TGAZIN_UF_UNIQUE ON FOCCO3I.TGAZIN_USUARIO_FILIAL(UPPER(LOGIN_USUARIO), EMPR_ID);

-- Comentários nas colunas
COMMENT ON TABLE FOCCO3I.TGAZIN_USUARIO_FILIAL IS 'Controle de acesso por filial/empresa para usuários';
COMMENT ON COLUMN FOCCO3I.TGAZIN_USUARIO_FILIAL.ID_USUARIO_FILIAL IS 'ID único do registro';
COMMENT ON COLUMN FOCCO3I.TGAZIN_USUARIO_FILIAL.LOGIN_USUARIO IS 'Login do usuário no sistema FOCCO';
COMMENT ON COLUMN FOCCO3I.TGAZIN_USUARIO_FILIAL.EMPR_ID IS 'ID da empresa/filial (FK para TEMPRESAS)';
COMMENT ON COLUMN FOCCO3I.TGAZIN_USUARIO_FILIAL.ATIVO IS 'S = Ativo, N = Inativo';
COMMENT ON COLUMN FOCCO3I.TGAZIN_USUARIO_FILIAL.DT_CADASTRO IS 'Data de cadastro do registro';
COMMENT ON COLUMN FOCCO3I.TGAZIN_USUARIO_FILIAL.DT_ALTERACAO IS 'Data da última alteração';

-- Grant de permissões
GRANT SELECT, INSERT, UPDATE, DELETE ON FOCCO3I.TGAZIN_USUARIO_FILIAL TO PUBLIC;

COMMIT;
